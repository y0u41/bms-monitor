/**
 ****************************************************************************************************
 * @file        led.c
 * @brief       LED 驱动 (LED0 -> PB5, LED1 -> PE5, 低电平点亮)
 * @note        引脚时钟与输出模式由 CubeMX 生成的 MX_GPIO_Init() 配置, 这里只做状态复位。
 ****************************************************************************************************
 */

#include "./BSP/LED/led.h"

/**
 * @brief     初始化 LED(确保两灯熄灭, 并作为运行状态指示)
 * @param     无
 * @retval    无
 */
void led_init(void)
{
    LED0(1);        /* LED0 熄灭 */
    LED1(1);        /* LED1 熄灭 */
}
