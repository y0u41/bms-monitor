/**
 ****************************************************************************************************
 * @file        ntc.h
 * @brief       NTC 10K B3950 温度换算（**纯查表 + 整数插值，⛔ 不用浮点**）
 * @note        1, ★★ **为什么不用浮点**：`Tech_Design.md` §4.2 的模块表写着 `app_soc.c` 是
 *                  **唯一允许用浮点的业务模块** ⇒ BSP 层一律定点/查表。
 *              2, ★ 拓扑与公式**从项目自己的文字里定死**（`Build.md` D11 前置第 2 条原文）：
 *                  `R_ntc = R_pull × V / (Vref − V)` ⇒ **NTC 在下、10K 上拉**；代入 `V = code/4095 × Vref`
 *                  后 **Vref 恰好约掉**：
 *                      **R_ntc = 10000 × code / (4095 − code)**
 *                  再按 B 参数式 `1/T = 1/T0 + ln(R/R0)/B`（R0 = 10kΩ @25℃、B = 3950）出温度。
 *                  ★ 自检点：**code 2047 ⇒ 25.0℃**（因为 25℃ 时 R_ntc = R_pull = 10kΩ）——
 *                  这一条是拓扑对错的**判决点**：接反了它会给出 55℃ 而本条立刻失败。
 *              3, ⚠️ **表是离线算好的**（每 16 个 code 一项、256 项、512 B），项间**线性插值**；
 *                  钳位到 [-40.0, +125.0]℃，**越界一律回 `NTC_ERR_RANGE`**（⛔ 不返回钳位值当读数）。
 *              4, ⚠️ **精度判决要等 D11 台架**：与参考温度计差 ≤2℃（`Build.md` §2 的 D11 DoD）。
 *                  本模块只保证"**换算公式与表一致**"（自检覆盖），⛔ 不保证实物精度。
 ****************************************************************************************************
 */

#ifndef __NTC_H
#define __NTC_H

#include "./SYSTEM/sys/sys.h"

#define NTC_OK          0u
#define NTC_ERR_RANGE   1u      /* ADC 码落在量程外（短路/开路/未接）⇒ **不是温度** */

/** 上拉电阻与 B 值（★ 改硬件时同批改这里；D11 的第一件事就是核对它们与实物一致） */
#define NTC_R_PULL_OHM  10000u
#define NTC_R0_OHM      10000u
#define NTC_B_VALUE     3950u
#define NTC_CODE_MAX    4095u

/**
 * @brief       12 位 ADC 码 → 温度（0.1℃）
 * @retval      `NTC_OK` / `NTC_ERR_RANGE`
 * @note        ⛔ 越界**不返回钳位值**：钳位值看起来像"一个很冷/很热的读数"，
 *              而实际上它是"根本没接/短路"—— 那正是 `§4.4` 说的"把不可知伪装成已知"。
 */
uint8_t     ntc_code_to_temp_x10(uint16_t code, int16_t *t_x10);

/** @brief ★ 离线自检：用**离线算出的真值**核对换算（⛔ 不需要接 NTC） */
uint16_t    ntc_selftest(void);

/** 取证出口（⛔ 不参与判据） */
uint16_t    ntc_selftest_result(void);

#endif
