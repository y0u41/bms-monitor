/**
 ****************************************************************************************************
 * @file        sht30.h
 * @brief       SHT30 / SHT31 温湿度传感器驱动（挂在 `g_bus_sens` = PB6/PB7 上）
 * @note        1, 本驱动**不再自带位带**（D3 / 审查 C-39 收口）：位操作全部走
 *                  `Drivers/BSP/SOFTI2C/` 的 `g_bus_sens` 实例。⛔ 不得改调 `g_bus_afe` ——
 *                  SHT30 与 AFE 共线就是违反 S6（SHT30 卡住总线 = 无意义跳闸）;
 *              2, 引脚口径唯一来源 = `Tech_Design.md` §2：PB6(SCL)/PB7(SDA) 上挂
 *                  INA226(0x40) + SHT30(0x44) + 24C02(0x50)，板载已有 4.7K 上拉，无需外接电阻；
 *              3, ★ **非阻塞**：单次测量高重复性最大 15ms（手册），所以把"发命令"和"取结果"
 *                  拆成两拍（S12）。⛔ 本驱动内不存在任何 `delay_ms`；
 *              4, 温度/湿度均以 0.1 为单位返回整数，避免在无 FPU 的 F103 上引入浮点库。
 * @note        移植来源：本项目自写（原 v1 自带私有位带 + `delay_ms(20)` 忙等）。
 *              改动点（v2，D3）：① 删私有 I²C 位带，改调 `softi2c_write()/softi2c_read()`；
 *                  ② `sht30_init()`（含 GPIO 初始化）拆成 `sht30_probe()`（只发地址探在位）——
 *                     总线由启动序列统一 `softi2c_init(&g_bus_sens)`，驱动不得反复改总线方向；
 *                     原先"用软复位命令当在位判据"改成了纯地址写（同效，且不带 3ms 忙等），
 *                     无人调用的 `sht30_soft_reset()` 一并删除；
 *                  ③ `sht30_read()` 的 `delay_ms(20)` 忙等换成两阶段 `sht30_measure()` + `SHT30_BUSY`。
 *              验证方式：D3 台架 —— 读数与参考温度计差 ≤0.5℃、同一总线 24C02 仍可读写、
 *                  拔掉 SHT30 不阻塞 INA226。⛔ 硬件在路上，本次**仅代码级 + 编译门禁**，未上机。
 ****************************************************************************************************
 */

#ifndef __SHT30_H
#define __SHT30_H

#include "./SYSTEM/sys/sys.h"

/* ===================== 器件地址 ===================== */
/* ADDR 引脚接 GND(默认) 时为 0x44; 接 VDD 时为 0x45 */
#define SHT30_I2C_ADDR          0x44

/* ===================== 返回码 ===================== */
#define SHT30_OK                0
#define SHT30_ERR_NACK          1       /* 器件无应答(没接 / 接线错 / 地址不对) */
#define SHT30_ERR_CRC           2       /* 数据 CRC 校验失败 */
#define SHT30_ERR_PARAM         3
#define SHT30_BUSY              4       /* ★ 已发出测量命令、还没到取读时刻：不是失败，保持上一次读数 */

/* 单次测量（高重复性）最大耗时 15ms（手册），取 20ms 留余量 */
#define SHT30_MEAS_WAIT_MS      20

/**
 * @brief       探测器件是否在位（只发地址，不碰总线方向、不复位）
 * @retval      SHT30_OK 表示在位；SHT30_ERR_NACK 表示没接/地址错
 * @note        ★ 调用前必须已经 `softi2c_init(&g_bus_sens)`。本函数可以被反复调用
 *              （没探到就每 2s 重试一次），所以它**不**清失败计数、**不**重配 GPIO。
 */
uint8_t sht30_probe(void);

/**
 * @brief       读温湿度（**两阶段、非阻塞**）
 * @param       temp_x10: 温度, 单位 0.1℃ (例: 265 表示 26.5℃)
 * @param       humi_x10: 湿度, 单位 0.1%RH
 * @retval      SHT30_OK      取到新一帧（并已为下一拍发出测量命令）
 *              SHT30_BUSY    上一拍刚触发，还没到 20ms —— 保持上一次读数，不算失败
 *              SHT30_ERR_*   通信/CRC 失败
 * @note        用法：按固定节拍反复调用即可（稳态下每拍返回一帧新数据）。
 *              首拍必返 BUSY，因为命令刚发出去。
 */
uint8_t sht30_measure(int16_t *temp_x10, uint16_t *humi_x10);

#endif
