/**
 ****************************************************************************************************
 * @file        app_ui.h
 * @brief       BMS 本地界面：LCD 三页（总况 / 单体电压 / 事件）+ 按键语义
 * @note        PRD.md FR-HMI-01/02/03/04 的代码落点；Build.md D2 的交付物。
 *
 * @note        ★ 本模块的三条边界（违反即回滚）：
 *                1) **只读快照、只发请求**（§4.2 模块职责）：界面不得做保护判断，
 *                   也不得驱动任何执行器 —— 所有开关动作只允许出现在 app_protect.c（S9）。
 *                   因此"解除锁定"在这里只是一个**请求**，通过 unlock hook 交给 app_protect 处置。
 *                2) 按键周期：D2 挂在遗留超循环上（约 20ms），D5 迁到 TaskUi。
 *                   ⚠️ §4.3 给的 TaskUi 周期是 200ms —— 那个周期**只够刷图，不够抓短按**
 *                   （人手一次按下约 80~150ms，两次轮询之间按完就会被整次漏掉，
 *                    表现为"有时按了没反应"）。迁移时必须把按键与刷图分开：
 *                    按键交给 10~20ms 的节拍（或 EXTI），200ms 只用于重绘。
 *                   记在 `附录C` 的 D5 待办里，不在本文件里偷偷改 §4.3 的口径。
 *                3) 不打印浮点、不 malloc：全部静态缓冲，数值一律按 §4.4 的定点量纲显示。
 *
 * @note        ⛔ 界面里出现的任何门限都只用于"上色/提示"，必须引用 app_config.h 的
 *              `APP_BMS_*`（电池量）—— 禁止用 `APP_ENV_*` 承载电池判据（C-38 / S7）。
 ****************************************************************************************************
 */

#ifndef __APP_UI_H
#define __APP_UI_H

#include "./SYSTEM/sys/sys.h"
#include "./App/app_data.h"

/* ==================== 页面编号（KEY1 按此顺序循环翻页） ==================== */
#define UI_PAGE_OVERVIEW        0       /* 总况：组压/电流/SOC/温度/告警等级/锁定态 */
#define UI_PAGE_CELLS           1       /* 单体电压：逐串 + 最高/最低/压差 */
#define UI_PAGE_EVENTS          2       /* 事件：最近若干条带时间戳（FR-HMI-03） */
#define UI_PAGE_COUNT           3

void        app_ui_init(void);                          /* 上电画第一页（内部含清屏） */
void        app_ui_task(uint32_t now_ms);               /* 周期调用：扫描按键 + 到点重绘 */

uint8_t     app_ui_page(void);                          /* 当前页号，供日志/协议回显 */

/* "长按 5s 解除锁定"的请求出口（S11：解除动作只能由 app_protect 执行）。
 * 未注册时界面只打印一行"已发出请求"并显示倒计时 —— 界面自己绝不改任何锁定状态。 */
void        app_ui_set_unlock_hook(void (*hook)(void));

/* "短按清除本地告警"的出口（等价 Modbus 线圈 0x0003，⛔ 不能解除三级锁定）。
 * 同上：未注册时只回显，不改状态。 */
void        app_ui_set_ack_hook(void (*hook)(void));

#endif
