/**
 ****************************************************************************************************
 * @file        app_bus.h
 * @brief       传感 I²C 总线的**跨任务互斥**（★ 只给 `g_bus_sens`，`g_bus_afe` 永不上锁）
 * @note        对应 `附录C` C-96 ⑥ 与 `Build.md` §8.4 M3（"M3 是 `g_bus_sens` 互斥的最晚落地时点"）。
 *
 * @note        ★ 为什么"上调度器"这一件事会连带出锁（不是顺手加的）：
 *              D3 之前整台机器是一个超循环，SHT30 与 24C02 的事务天然串行 —— 那个"天然"当时
 *              没有写在任何地方，所以它消失的时候也不会有任何报错。上调度器后 legacy 容器与
 *              D10 的 INA226 读者分处两个任务，两条帧交错 → 互相咬出 NACK，而 NACK 记的是
 *              **同一条总线的 `fail`**（C-39 的记账口径）⇒ 别人的撕裂被读成"这颗器件坏了"。
 *
 * @note        ★ 为什么锁加在**驱动入口**而不是要求调用者自觉：
 *              见 `softi2c.h` 的 `lock`/`unlock` 钩子 —— 新增一个从机驱动（D10 INA226）不必
 *              记得加锁，也就不会漏。**本模块只提供钩子的实现（拿锁/还锁），不改变谁都能调
 *              `sht30_read()` 这个事实。**
 *
 * @note        ⛔ **AFE 那条总线必须永远 `lock == NULL`**（S6 / S1~S3）：
 *              保护路径一旦被一把传感总线上的锁挡住，"过流了但还在等 24C02 写完"就是拒动作。
 *              `app_bus_init()` 里只注册 `g_bus_sens` 一个实例，这个不对称是**故意的**。
 *
 * @note        ⚠️ 调度器启动前（启动序列里的 `softi2c_init` / `at24cxx_selftest` / `th_detect`）
 *              只有一个调用者，钩子直接放行 —— 否则 `app_main()` 会在建任务之前把自己锁死。
 ****************************************************************************************************
 */

#ifndef __APP_BUS_H
#define __APP_BUS_H

#include "./SYSTEM/sys/sys.h"

/**
 * @brief       建静态互斥量并把钩子登记进 `g_bus_sens`
 * @note        必须在 `softi2c_init(&g_bus_sens)` **之后**、`app_tasks_create()` **之前**调用。
 * @retval      0 = 成功; 1 = 互斥量创建失败（静态内存参数写错）
 */
uint8_t app_bus_init(void);

/**
 * @brief       取"拿锁时锁已被别人持有"的累计次数（★ 永久件，⛔ 不是判据）
 * @note        为什么必须有它：这把锁本身**不可观测** —— "锁生效"与"根本没人抢"在两条总线的
 *              `fail` 计数里同为 0，完全同形。本计数 = `Build.md` §8.4 **V8 的存在性探针**
 *              （V8 的"两条总线增量 = 0"只有在 `contend > 0` 时才有意义，否则就是空过）。
 *              落点 = `app_bus.c` 的拿锁钩子，判据 = `uxSemaphoreGetCount() == 0`。
 */
uint32_t app_bus_contention_count(void);

/**
 * @brief       取"拿锁超时"的累计次数（那笔事务**没发生**，`softi2c.c` 已给它记一次总线失败）
 * @note        ⚠️ 必须与上一条**分开数**：两者混成一个数就分不出"抢过并等到了"与"抢输了"，
 *              而后者才是要紧的（它的修法 = 查持有者为什么僵住，⛔ 不是查器件坏没坏）。
 */
uint32_t app_bus_lock_timeout_count(void);

#endif
