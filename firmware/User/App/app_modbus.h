/**
 ****************************************************************************************************
 * @file        app_modbus.h
 * @brief       Modbus RTU **从机**（§6.1 寄存器表 / 线圈表 + §6.2 故障位图），跑在 `TaskComm`（10ms）
 * @note        1, ★ 本文件 = `app_tasks.c` 里那句 `TODO(D9): Modbus RTU 收帧/回帧（app_modbus.c）`
 *                  的落点 —— 也就是 `Tech_Design.md` §4.3 任务表 `TaskComm` 行的职责。
 *                  **物理层在 `Drivers/BSP/RS485/`**：本文件只做协议（CRC16 / 功能码 / 寄存器映射），
 *                  ⛔ 不碰任何寄存器名、引脚、DMA（S15 的分层口径 + G7-① 的机械检查）。
 *              2, ★★ **本轮是把 D9 的从机**提前到 D6 交付**（本人 2026-09-28 决定）**。
 *                  动它的**唯一理由**：它是"完全不依赖 A 采样板"的最大一块硬阻塞
 *                  （§4.3 判据①"第三方 Modbus 工具能读全部寄存器"必须先有从机才谈得上）；
 *                  而 `附录C` C-100 把 Modbus 排到 D9 的**原因并不是"不该写"**，
 *                  而是"**验收**之前必须先证明应答方是谁"（M0 三条判据）。
 *                  ⇒ ★ 因此本文件交付的**只是"能应答"这一半**，⛔ **不构成 C-100 的 M0 已完成**：
 *                    M0 的①负向判据（向未实现地址发 03 期望超时/异常码）现在**可以做了**
 *                    —— 本版恰好实现了它要的那个"未实现地址回异常码"的行为；
 *                    但②活证据（改一个可见常数、屏与工具同一次采样同步变）与③逐项对表
 *                    仍要等 RS485 主机与第三方工具接上，**那一步没做之前，本模块一行都不算验收**。
 *              3, ⛔ **线圈绝不直接驱动执行器**（§6.1 原文 + S9）：线圈只写"意图"，
 *                  交给 `app_protect_set_intent()`，真正的动作在 `app_protect_step()` 里。
 *                  这是 G7-⑦ 机械守住的东西（`User/` 下 `actuator_*(` 只允许出现在 app_protect）。
 *              4, ★ **本模块是快照的纯读者 + 意图的纯写者**（§4.2 单向数据流）：
 *                  它不写 `bms_raw_t` / `bms_derived_t` / `bms_alarm_t`，也不碰任何执行器。
 *              5, ⛔ 中断里不得调用（S8）：本模块只在任务上下文跑，且内部**没有任何阻塞等待**
 *                  —— 唯一的阻塞是 `app_data_read()` 的有界重试（不涉及硬件）。
 *
 * @note        ★★ **本轮实现/未实现清单（⛔ 必须原样读，不得按"表里都有 ⇒ 都实现了"理解）**
 *              已实现（可读）：
 *                `0x0000~0x0032` 全部 51 个寄存器（含 §6.1 的温度无效码与两个 link 位图）、
 *                `0x0200~0x0241` 日志读协议、`0x0300` 固件版本、`0x0302` 从机地址（R/W，**RAM 内即时生效**）、
 *                `0x0303` 波特率编码（R/W，**回帧之后**才切换）、`0x0305` 日志格式版本；
 *                功能码 `0x03 / 0x06 / 0x10 / 0x01 / 0x05`。
 *              未实现（**按"回异常码 0x02"处理，⛔ 绝不回 0**）：
 *                `0x0033~0x00FF` 预留区、`0x0100~0x014F` **门限参数区**（参数区本身还没建 ⇒
 *                  回 0 等于向上位机谎报"所有门限 = 0"）、`0x0301`（读回 **`0xFFFF` = 无效**）、
 *                `0x0304`（参数提交：**没有参数区可提交**）。
 *                ★ 线圈 `0x0002`（一键上报，WiFi 是加分项）与 `0x0004`（解除锁定，**需鉴权 = P2**）
 *                  同样回异常码 0x02；**`0x0003`（清除本地告警）已实现**，走 `app_ui_request_ack()`。
 *              ⚠️ **两处本版写死、必须跟着一起说清的边界**：
 *                a) **从机地址与波特率只存在于 RAM** ⇒ 掉电回到 `app_config.h` 的默认值。
 *                   "写进去了但重启就没了"与"写进去了"在 Modbus 读回上**完全同形**
 *                   ⇒ 落盘要等参数区（§13 的 `APP_PARAM_A_ADDR` 今天只有地址、没有实现），
 *                   登记为债务（`附录C` C-117）。
 *                b) `0x0021`（均衡状态位图）**恒 0，且这不是"未实现"** —— 本版**没有均衡功能**
 *                   （P2），"没有任何一串在均衡"是一个**为真的**读数。⛔ 但上位机不得据此认为
 *                   均衡器存在：P2 启用时这一格才会真的动。
 *
 * @note        ★ 寄存器地址的**唯一来源 = `Tech_Design.md` §6.1**，本文件不复述数值表，
 *              只在每个分支上写地址并在必要处引 §6.1 的行。⚠️ **本轮同步了 §6.1 的四处**
 *              （0x0020 位定义 / 0x0030 定义 / 0x0300 打包格式 / 0x0202~0x0241 的条数矛盾），
 *              理由与逐条对照见 `附录C` **C-117**（协议改动走 G4）。
 ****************************************************************************************************
 */

#ifndef __APP_MODBUS_H
#define __APP_MODBUS_H

#include "./SYSTEM/sys/sys.h"

/* ===================== 功能码（§6.1 的"功能码"一行） ===================== */
#define MB_FC_READ_COILS        0x01u
#define MB_FC_READ_HOLDING      0x03u
#define MB_FC_WRITE_COIL        0x05u
#define MB_FC_WRITE_ONE         0x06u
#define MB_FC_WRITE_MULTI       0x10u

/* ===================== 异常码（Modbus 规约；本版只会用到前三个 + 设备故障） ===================== */
#define MB_EXC_ILLEGAL_FUNC     0x01u   /* 不支持的功能码 */
#define MB_EXC_ILLEGAL_ADDR     0x02u   /* ★ 地址不存在 **或本版未实现**（口径见文件头） */
#define MB_EXC_ILLEGAL_VALUE    0x03u   /* 数量/取值非法（qty=0 / >125 / 线圈值不是 0xFF00/0x0000…） */
#define MB_EXC_DEVICE_FAILURE   0x04u   /* 本机取不到一致快照（`app_data_read()` 返回 2）⇒ 不许回撕裂帧 */

/* ===================== 广播地址（⛔ 不是合法的从机地址，见 `app_config.h` §12.13） ===================== */
#define MB_ADDR_BROADCAST       0x00u

/* ===================== 0x0020「执行器状态」位定义（★ 本轮新增，已同步 §6.1） =====================
 * ★ 低 3 位的位序**复用一个已有来源**，⛔ 不许在本文件另立一套：位 0/1/2 = `actuator.h` 的
 *   `ACT_ST_CHG / ACT_ST_DSG / ACT_ST_PRE`（`app_log.h` 的 `EV_MOS_CLOSE` 注也钉着同一条）。
 *   "充/放哪一位是 1"这件事在本项目历史上被写反过一次（1=DSG 2=CHG），所以它只允许有一个答案。 */
#define MB_ACT_BIT_CHG          0x01u
#define MB_ACT_BIT_DSG          0x02u
#define MB_ACT_BIT_PRE          0x04u
#define MB_ACT_BIT_LATCH        0x08u   /* 三级锁定（§5.2 的 FAULT_LATCHED） */
#define MB_ACT_BIT_HW_ACTED     0x10u   /* AFE 硬件层已动作（`bms_alarm_t.hw_layer_state`） */
#define MB_ACT_BIT_UNKN         0x8000u /* ★ **不可知**：引脚状态没有可信来源 ⇒ 低 3 位不得按"断开"读
                                         *   （`app_data.h` 的 `BMS_HW_UNKN` 同一条口径） */

/* ===================== 固件版本（§6.1 的 0x0300「主/次/修打包」） =====================
 * ⚠️ 打包格式（高位在前）= `(主 << 12) | (次 << 4) | 修` ⇒ 当前 = **`0x0230` = v0.23.0**。
 *   ★ 本行与 `Build.md` 交付表的版号标签是**同一个人写的两个地方**（计数耦合）：
 *     交付构建改名的**那一轮**必须同批改这三行（`附录C` 的计数耦合口径）。
 *   ⚠️ v0.22（本模块第一次上机的那一版）里这三行是 **21** ⇒ 协议读回 `0x0210`；
 *     改名到 v0.23 的原因是**同一轮内**发现并修掉一处取值缺陷（六格 RTC 各读一次 ⇒ 可能跨秒，
 *     且一次请求对外写全局 `calendar` 12 次）—— 见 `.c` 的 `mb_time_load()` 注。 */
#define MB_FW_VER_MAJOR         0u
#define MB_FW_VER_MINOR         23u
#define MB_FW_VER_PATCH         0u
#define MB_FW_VER_PACKED        ((uint16_t)(((MB_FW_VER_MAJOR & 0xFu) << 12) | \
                                            ((MB_FW_VER_MINOR & 0xFFu) << 4) | \
                                            (MB_FW_VER_PATCH & 0xFu)))

/* ===================== 对外的三个动作 ===================== */

/**
 * @brief       上电初始化：物理层 + 协议状态（⛔ 不建任务、不开中断 —— 那些在 `rs485_init()` 里）
 * @param       baud  波特率（`APP_MB_BAUD_19200` 等）
 * @retval      0 = 成功；非 0 = 物理层失败（`RS485_ERR_*`）
 * @note        ⛔ 必须在 `app_nvic_init()` **之后**、`vTaskStartScheduler()` **之前**调用。
 */
uint8_t  app_modbus_init(uint32_t baud);

/**
 * @brief       `TaskComm` 的周期体（10ms）：取帧 → 校验 → 执行 → 回帧
 * @param       now_ms  ★ 必须是 **`HAL_GetTick()` 口径**（与快照时间戳同钟，理由同
 *                      `app_protect.h` 的 `app_protect_step()` —— 两个计数器起点差一个
 *                      "调度器启动时刻"，混用会让新鲜度算出回绕的巨大值）。
 * @note        ⛔ 本函数内部不得阻塞：最坏路径 = 一次 `app_data_read()`（有界重试）+ 一次
 *              `rs485_tx_start()`（异步 DMA）。10ms 的周期预算是**富余的**（回帧 256 字节
 *              @19200 = 133ms，而那段时间由**物理层**在搬，本任务只负责启动它）。
 */
void     app_modbus_step(uint32_t now_ms);

/**
 * @brief       ★ 无需外部设备的自检：CRC16 已知答案 + 一条合成请求的响应结构
 * @retval      0 = 两项都过；1 = CRC 已知答案不符；2 = 响应结构不符（地址/功能码/字节数/CRC）
 * @note        ★ 为什么值得写：这是本模块**唯一能在没有 Modbus 主机、没有 RS485 转换器、
 *              甚至没有插 P5 跳线的情况下**跑起来的端到端判据。它证明的是
 *              "字节序 + CRC 位序 + 功能码 0x03 的响应骨架 + 长度计算"这四件事。
 *              ⛔ 它**不证明**寄存器内容正确（内容依赖快照，是另一条判据）、
 *                 **不证明**收发器与线序（那要台架）、也**不证明** §6.1 的量纲。
 *              ⚠️ 自检把响应写进**临时缓冲**，⛔ 不碰 `rs485` 的发送缓冲、不上总线。
 */
uint8_t  app_modbus_selftest(void);

/* ===================== 取证出口（⛔ 不参与任何判据） =====================
 * 口径同 `app_bus.c` 的 `contend/lock_to` 与 `app_tasks.c` 的那五个 getter：
 * 它们回答"发生过没有、发生了几次"，不回答"该不该动作"。消费点 = 页 3 / D9 的串口命令入口。 */
uint32_t app_modbus_rx_frames(void);        /* 收到的、地址匹配的帧 */
uint32_t app_modbus_answered(void);         /* 真正回了帧的次数（广播不计） */
uint32_t app_modbus_crc_errors(void);       /* CRC 不过而沉默的次数 */
uint32_t app_modbus_addr_mismatch(void);    /* 地址不是本机（且不是广播）而沉默的次数 */
uint32_t app_modbus_exceptions(void);       /* 回了异常码的次数 */
uint32_t app_modbus_tx_errors(void);        /* 回帧启动失败（物理层忙/拒收）次数 */
uint8_t  app_modbus_addr(void);             /* 当前从机地址（RAM 值，⛔ 不等于"掉电后还是它"） */
uint8_t  app_modbus_baud_code(void);        /* 当前波特率编码（§6.1 的 0x0303 口径） */

#endif
